/* Flatten nested dictionaries to dotted keys for the `t()` helper     */
/* ------------------------------------------------------------------ */
type FlattenKeys<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string
    ? P extends ""
      ? K
      : `${P}.${K}`
    : FlattenKeys<T[K], P extends "" ? K : `${P}.${K}`>;
}[keyof T & string];

export type MessageKey = FlattenKeys<Messages>;

type FlatDict = Record<string, string>;

function flatten(obj: Record<string, unknown>, prefix = ""): FlatDict {
  const out: FlatDict = {};
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") {
      out[path] = value;
    } else {
      Object.assign(out, flatten(value as Record<string, unknown>, path));
    }
  }
  return out;
}

export const dictionaries: Record<Locale, FlatDict> = {
  en: flatten(en),
  th: flatten(th),
};
